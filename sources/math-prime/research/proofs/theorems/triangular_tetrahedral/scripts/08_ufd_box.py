_roots = np.roots([1.0, 0.0, -4.0, 6.0])
L1F = float([z.real for z in _roots if abs(z.imag) < 1e-9][0])
ZF = complex([z for z in _roots if z.imag > 1e-9][0])


def t2_float(u):
    a, b, c = u
    s1 = a + b*L1F + c*L1F*L1F
    s2 = a + b*ZF + c*ZF*ZF
    return s1*s1 + 2*abs(s2)**2


def lll_t2(basis, delta=0.99):
    """LLL reduction of a basis for the T2 form, in floating point (guidance for the search of 6.4)."""
    def emb(u):
        a, b, c = u
        s1 = a + b*L1F + c*L1F*L1F
        s2 = a + b*ZF + c*ZF*ZF
        return (s1, math.sqrt(2)*s2.real, math.sqrt(2)*s2.imag)

    def dot(x, y):
        return sum(p*q for p, q in zip(x, y))

    def gso(B):
        V = [emb(v) for v in B]
        Bs, mu = [], [[0.0]*3 for _ in range(3)]
        for i in range(3):
            w = list(V[i])
            for j in range(i):
                mu[i][j] = dot(V[i], Bs[j])/dot(Bs[j], Bs[j])
                w = [x - mu[i][j]*y for x, y in zip(w, Bs[j])]
            Bs.append(w)
        return Bs, mu
    B = [tuple(v) for v in basis]
    k = 1
    while k < 3:
        for j in range(k - 1, -1, -1):
            _, mu = gso(B)
            q = round(mu[k][j])
            if q:
                B[k] = tuple(x - q*y for x, y in zip(B[k], B[j]))
        Bs, mu = gso(B)
        if dot(Bs[k], Bs[k]) >= (delta - mu[k][k - 1]**2)*dot(Bs[k - 1], Bs[k - 1]):
            k += 1
        else:
            B[k], B[k - 1] = B[k - 1], B[k]
            k = max(k - 1, 1)
    return B


def search_generator(p, g, box=3):
    """Elements of P(p,g) with |N| = p^deg g among small combinations of a T2-reduced basis; least T2 first."""
    target = p**(len(g) - 1)
    red = lll_t2(lattice_basis(p, g))
    found = set()
    for co in itertools.product(range(-box, box + 1), repeat=3):
        u = tuple(sum(co[i]*red[i][j] for i in range(3)) for j in range(3))
        if u != (0, 0, 0) and abs(norm(u)) == target:
            found.add(u)
    return sorted(found, key=lambda u: (round(t2_float(u), 9), u))


