# ---------------------------------------------------------------- polynomials over F_p
def f_mod(p):
    return (6 % p, (-4) % p, 0, 1)


def p_eval(poly, x, p):
    s = 0
    for co in reversed(poly):
        s = (s*x + co) % p
    return s


def p_mul(u, v, p):
    w = [0]*(len(u) + len(v) - 1)
    for i, x in enumerate(u):
        for j, y in enumerate(v):
            w[i + j] = (w[i + j] + x*y) % p
    return tuple(w)


def p_rem(u, g, p):
    """Remainder of u modulo the monic polynomial g over F_p, as a tuple of length deg g."""
    d = len(g) - 1
    u = [x % p for x in u] + [0]*max(0, d - len(u))
    for i in range(len(u) - 1, d - 1, -1):
        co = u[i]
        if co:
            for j in range(d + 1):
                u[i - d + j] = (u[i - d + j] - co*g[j]) % p
    return tuple(u[:d])


def p_div_linear(u, r, p):
    """(quotient, remainder) of u by t - r over F_p (synthetic division)."""
    n = len(u) - 1
    q = [0]*n
    acc = 0
    for i in range(n, 0, -1):
        acc = (acc*r + u[i]) % p
        q[i - 1] = acc
    rem = (acc*r + u[0]) % p
    return tuple(q), rem


def lin(r, p):
    """The monic polynomial t - r over F_p."""
    return ((-r) % p, 1)


def gstr(g, p):
    d = len(g) - 1
    if d == 1:
        r = (-g[0]) % p
        return "t" if r == 0 else f"t - {r}"
    terms = []
    for i in range(d, -1, -1):
        co = g[i]
        if co == 0:
            continue
        mon = "" if i == 0 else ("t" if i == 1 else f"t^{i}")
        terms.append((str(co) if co != 1 or i == 0 else "") + mon)
    return " + ".join(terms)


def factor_f(p):
    """The monic irreducible factors of f mod p with multiplicities, read off from the roots (proof: 6.2(a))."""
    fp = f_mod(p)
    roots = [r for r in range(p) if p_eval(fp, r, p) == 0]
    if not roots:
        return 'inert', [(fp, 1)]
    if len(roots) == 3:
        return 'split', [(lin(r, p), 1) for r in roots]
    if len(roots) == 2:
        dbl = [r for r in roots if (3*r*r - 4) % p == 0]
        if len(dbl) != 1:
            return 'unexpected', []
        rs = [r for r in roots if r != dbl[0]][0]
        return 'double', [(lin(dbl[0], p), 2), (lin(rs, p), 1)]
    r = roots[0]
    q, rem = p_div_linear(fp, r, p)
    if p_eval(q, r, p) != 0:
        return 'lin*quad', [(lin(r, p), 1), (q, 1)]
    return 'triple', [(lin(r, p), 3)]


def pattern_ok(p, kind, facs):
    """The factors multiply back to f mod p, and each factor of degree 2 or 3 has no root (so is irreducible)."""
    prod = (1,)
    for g, e in facs:
        for _ in range(e):
            prod = p_mul(prod, g, p)
    if prod != f_mod(p):
        return False
    for g, e in facs:
        if len(g) - 1 >= 2 and any(p_eval(g, x, p) == 0 for x in range(p)):
            return False
    return kind != 'unexpected'


# ---------------------------------------------------------------- prime lattices
def reductions(p, g):
    """t^0, t^1, t^2 modulo (p, g), as tuples of length deg g."""
    return [p_rem((0,)*i + (1,), g, p) for i in range(3)]


def in_P(beta, p, g, red=None):
    red = red if red is not None else reductions(p, g)
    return all((beta[0]*red[0][j] + beta[1]*red[1][j] + beta[2]*red[2][j]) % p == 0 for j in range(len(g) - 1))


def lattice_basis(p, g):
    """Columns p e_i (i < deg g) and e_i - (t^i mod g) (i >= deg g): an upper triangular basis of P(p,g)."""
    d = len(g) - 1
    red = reductions(p, g)
    cols = []
    for i in range(3):
        col = [0, 0, 0]
        if i < d:
            col[i] = p
        else:
            for j in range(d):
                col[j] = -red[i][j]
            col[i] = 1
        cols.append(tuple(col))
    return cols


def rows_of(cols):
    return [[cols[j][i] for j in range(3)] for i in range(3)]


def det3(M):
    return (M[0][0]*(M[1][1]*M[2][2] - M[1][2]*M[2][1]) - M[0][1]*(M[1][0]*M[2][2] - M[1][2]*M[2][0])
            + M[0][2]*(M[1][0]*M[2][1] - M[1][1]*M[2][0]))


def adj3(M):
    """Adjugate (transpose of the cofactor matrix): M adj3(M) = det(M) I."""
    def cof(i, j):
        r = [x for x in range(3) if x != i]
        c = [x for x in range(3) if x != j]
        return (-1)**(i + j)*(M[r[0]][c[0]]*M[r[1]][c[1]] - M[r[0]][c[1]]*M[r[1]][c[0]])
    return [[cof(j, i) for j in range(3)] for i in range(3)]


def matmul(A, B):
    return [[sum(A[i][k]*B[k][j] for k in range(3)) for j in range(3)] for i in range(3)]


def index_matrix(pi, p, g):
    """C = B^-1 M(pi) if it is an integer matrix, else None (B the basis matrix of P(p,g))."""
    B = rows_of(lattice_basis(p, g))
    dB = det3(B)
    num = matmul(adj3(B), [list(r) for r in matrix(pi)])
    if any(x % dB for row in num for x in row):
        return None
    return [[x // dB for x in row] for row in num]


def generates(pi, p, g):
    """The exact checks of the index lemma 6.1(d) and its conclusion P(p,g) = pi R.

    Returns a dict of booleans: pi in P(p,g); |N(pi)| = p^deg g; C = B^-1 M(pi) integral with det +-1;
    every basis vector of P(p,g) divisible by pi (so P(p,g) is contained in pi R; the converse is 6.1(b))."""
    d = len(g) - 1
    C = index_matrix(pi, p, g)
    return {
        'in': in_P(pi, p, g),
        'norm': abs(norm(pi)) == p**d,
        'unimodular': C is not None and det3(C) in (1, -1),
        'basis_divisible': all(divides(pi, col) is not None for col in lattice_basis(p, g)),
        'columns_in_P': all(in_P(col, p, g) for col in zip(*matrix(pi))),
    }


def is_unit(u):
    return norm(u) in (1, -1)


def associate(u, v):
    q = divides(v, u)
    return q is not None and is_unit(q)


def tstr(u):
    a, b, c = u
    parts = []
    for co, mon in ((c, "l^2"), (b, "l"), (a, "")):
        if co == 0:
            continue
        s = ("-" if co < 0 else "+") + " "
        mag = abs(co)
        parts.append(s + (str(mag) if (mag != 1 or mon == "") else "") + mon)
    if not parts:
        return "0"
    out = " ".join(parts)
    return out[2:] if out.startswith("+ ") else "-" + out[2:]


