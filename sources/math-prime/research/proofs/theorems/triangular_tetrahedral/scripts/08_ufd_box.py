def pigeonhole(p, r):
    """The box principle of 6.3, run: returns (beta, x, (B0,B1,B2), number of points examined)."""
    Bs = box_sizes(p)
    vals = [p_eval(bv, r, p) for bv in BASIS]
    seen = {}
    count = 0
    for c in itertools.product(range(Bs[0] + 1), range(Bs[1] + 1), range(Bs[2] + 1)):
        count += 1
        res = (c[0]*vals[0] + c[1]*vals[1] + c[2]*vals[2]) % p
        if res in seen:
            x = tuple(ci - di for ci, di in zip(c, seen[res]))
            beta = tuple(sum(x[i]*BASIS[i][j] for i in range(3)) for j in range(3))
            return beta, x, Bs, count
        seen[res] = c
    return None, None, Bs, count


