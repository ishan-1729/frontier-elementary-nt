def generator(p, g):
    if (p, g) not in GEN:
        kind, facs = factor_f(p)
        for gg, ee in facs:
            dg = len(gg) - 1
            if dg == 1:
                GEN[(p, gg)] = construct(p, (-gg[0]) % p)
        for gg, ee in facs:
            dg = len(gg) - 1
            if dg == 2:
                (pr,) = [GEN[(p, h)] for h, _ in facs if len(h) == 2]
                GEN[(p, gg)] = scal(norm(pr)//p, adj(pr))
            elif dg == 3:
                GEN[(p, gg)] = (p, 0, 0)
    return GEN[(p, g)]


def factorize(alpha, largest_first=False):
    """Divide out prime elements until a unit is left; returns (unit, list of labels (p, g))."""
    labels = []
    while not is_unit(alpha):
        n = abs(norm(alpha))
        fac = sp.factorint(n)
        require(f"factorint of {n} is exact", math.prod(q**ee for q, ee in fac.items()) == n)
        p = max(fac) if largest_first else min(fac)
        for g, ee in factor_f(p)[1]:
            if in_P(alpha, p, g):
                nxt = divides(generator(p, g), alpha)
                require(f"the generator of P({p},{gstr(g, p)}) divides alpha", nxt is not None)
                alpha = nxt
                labels.append((p, g))
                break
        else:
            require(f"6.2: {alpha} lies in some P({p},g)", False)
    return alpha, labels


