def icbrt_floor(x):
    """Largest integer B >= 0 with B^3 <= x (x a nonnegative Fraction)."""
    lo, hi = 0, 1
    while Fr(hi**3) <= x:
        hi *= 2
    while hi - lo > 1:
        mid = (lo + hi)//2
        if Fr(mid**3) <= x:
            lo = mid
        else:
            hi = mid
    return lo


