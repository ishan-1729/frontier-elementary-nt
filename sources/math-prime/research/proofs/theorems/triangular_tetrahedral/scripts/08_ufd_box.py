def bernstein(lo, hi):
    """Exact tensor Bernstein coefficients (degree 3 in each variable) of F on the box [lo, hi]."""
    w = [hi[i] - lo[i] for i in range(3)]
    A = [[[Fr(0)]*4 for _ in range(4)] for _ in range(4)]
    for (e0, e1, e2), co in FCO.items():
        for i in range(e0 + 1):
            ci = co*comb(e0, i)*lo[0]**(e0 - i)*w[0]**i
            for j in range(e1 + 1):
                cj = ci*comb(e1, j)*lo[1]**(e1 - j)*w[1]**j
                for k in range(e2 + 1):
                    A[i][j][k] += cj*comb(e2, k)*lo[2]**(e2 - k)*w[2]**k

    def tr(vec):
        return [sum(Fr(comb(I, i), comb(3, i))*vec[i] for i in range(I + 1)) for I in range(4)]
    for i in range(4):
        for j in range(4):
            A[i][j] = tr(A[i][j])
    for i in range(4):
        for k in range(4):
            col = tr([A[i][j][k] for j in range(4)])
            for j in range(4):
                A[i][j][k] = col[j]
    for j in range(4):
        for k in range(4):
            col = tr([A[i][j][k] for i in range(4)])
            for i in range(4):
                A[i][j][k] = col[i]
    return A


